""""Sparse matrix materialisation and compact report summaries."""
from __future__ import annotations

import csv
import gzip
import heapq
import json
from collections import Counter
from pathlib import Path

from .config import ConfigError
from .io_utils import atomic_text


def pair_path(matrix_dir: Path, sample: str, prefix: str = "raw") -> Path:
    return matrix_dir / f"{sample}.{prefix}_molecule_pairs.parquet"


def summary_path(matrix_dir: Path, sample: str, prefix: str = "raw") -> Path:
    return matrix_dir / f"{sample}.{prefix}_matrix_summary.json"


def _duckdb():
    try:
        import duckdb  # type: ignore
    except ImportError as exc:
        raise ConfigError("Sparse matrices require duckdb; install the tagforge matrix dependencies") from exc
    return duckdb


def build_sparse_matrix(source: Path, matrix_dir: Path, sample: str, barcode_col: str, feature_col: str, *, prefix: str = "raw"):
    """Aggregate molecule records with a disk-spilling SQL engine."""
    duckdb = _duckdb()
    matrix_dir.mkdir(parents=True, exist_ok=True)
    pairs, summary = pair_path(matrix_dir, sample, prefix), summary_path(matrix_dir, sample, prefix)
    con = duckdb.connect()
    b1, b2 = barcode_col.replace('"', '""'), feature_col.replace('"', '""')
    source_sql, output_sql = str(source).replace("'", "''"), str(pairs).replace("'", "''")
    try:
        parquet_source = source_sql + "/*.parquet" if source.is_dir() else source_sql
        reader = f"read_parquet('{parquet_source}')" if source.suffix == ".parquet" else (
            f"read_csv_auto('{source_sql}', delim='\\t', header=true, compression='gzip')"
        )
        con.execute(f"CREATE TEMP TABLE pairs AS SELECT \"{b1}\" AS barcode1, \"{b2}\" AS feature, COUNT(*)::BIGINT AS molecule_count FROM {reader} GROUP BY 1, 2")
        con.execute(f"COPY pairs TO '{output_sql}' (FORMAT PARQUET, COMPRESSION ZSTD)")
        feature_counts = dict(con.execute("SELECT feature, SUM(molecule_count) FROM pairs GROUP BY feature").fetchall())
        pb_rows = con.execute("SELECT barcode1, SUM(molecule_count), COUNT(*) FROM pairs GROUP BY barcode1").fetchall()
    finally:
        con.close()
    molecule_bins, protein_bins, molecule_heap, protein_heap = [0] * 8, [0] * 8, [], []
    for barcode, molecules, proteins in pb_rows:
        molecules, proteins = int(molecules), int(proteins)
        molecule_bins[min(molecules, 8) - 1] += 1; protein_bins[min(proteins, 8) - 1] += 1
        for heap, score in ((molecule_heap, molecules), (protein_heap, proteins)):
            item = (score, barcode, molecules, proteins)
            if len(heap) < 20: heapq.heappush(heap, item)
            elif item > heap[0]: heapq.heapreplace(heap, item)
    top = lambda heap: [{"PB": row[1], "Molecules": row[2], "Proteins": row[3]} for row in sorted(heap, reverse=True)]
    payload = {"schema_version": 1, "pair_table": pairs.name, "barcode_count": sum(molecule_bins), "feature_counts": feature_counts,
               "pi_seq": {"total": sum(molecule_bins), "molecule_bins": molecule_bins, "protein_bins": protein_bins,
                          "top_molecules": top(molecule_heap), "top_proteins": top(protein_heap)}}
    with atomic_text(summary) as handle:
        json.dump(payload, handle, separators=(",", ":"), sort_keys=True)
    return pairs, summary


def load_summary(path: Path):
    with path.open(encoding="utf-8") as handle:
        payload = json.load(handle)
    return int(payload["barcode_count"]), Counter({k: int(v) for k, v in payload["feature_counts"].items()}), payload.get("pi_seq")


def export_matrix(pairs: Path, output: Path, fmt: str, barcode_header: str = "Barcode1"):
    duckdb = _duckdb(); con = duckdb.connect()
    try:
        source_sql = str(pairs).replace("'", "''")
        if fmt == "parquet":
            target = str(output).replace("'", "''")
            con.execute(f"COPY (SELECT * FROM read_parquet('{source_sql}')) TO '{target}' (FORMAT PARQUET, COMPRESSION ZSTD)")
            return [output]
        rows = con.execute(f"SELECT barcode1, feature, molecule_count FROM read_parquet('{source_sql}') ORDER BY 1, 2").fetchall()
    finally:
        con.close()
    if fmt == "mtx":
        barcodes = sorted({row[0] for row in rows}); features = sorted({row[1] for row in rows})
        barcode_index = {value: index + 1 for index, value in enumerate(barcodes)}
        feature_index = {value: index + 1 for index, value in enumerate(features)}
        prefix = output.name.removesuffix(".mtx.gz").removesuffix(".mtx")
        barcode_path = output.with_name(f"{prefix}.barcodes.tsv.gz")
        feature_path = output.with_name(f"{prefix}.features.tsv.gz")
        with gzip.open(output, "wt", encoding="utf-8", newline="", compresslevel=3) as handle:
            handle.write("%%MatrixMarket matrix coordinate integer general\n% Generated by TagForge\n")
            handle.write(f"{len(barcodes)} {len(features)} {len(rows)}\n")
            for barcode, feature, count in rows: handle.write(f"{barcode_index[barcode]} {feature_index[feature]} {count}\n")
        for path, values in ((barcode_path, barcodes), (feature_path, features)):
            with gzip.open(path, "wt", encoding="utf-8", newline="", compresslevel=3) as handle: handle.write("\n".join(values) + "\n")
        return [output, barcode_path, feature_path]
    if fmt != "tsv": raise ConfigError("matrix export format must be parquet, mtx, or tsv")
    features, by_barcode = sorted({row[1] for row in rows}), {}
    for barcode, feature, count in rows: by_barcode.setdefault(barcode, {})[feature] = count
    with gzip.open(output, "wt", encoding="utf-8", newline="", compresslevel=3) as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n"); writer.writerow([barcode_header] + features)
        for barcode, counts in sorted(by_barcode.items()): writer.writerow([barcode] + [counts.get(f, 0) for f in features])
    return [output]

